// Сопоставление категории товара с профильной услугой (для перелинковки товар→услуга).
export function serviceForCategory(name: string | null | undefined): ServiceItem | null {
  const n = (name ?? "").toLowerCase();
  if (!n) return null;
  let key: string | null = null;
  if (/шлагбаум/.test(n)) key = "barrier";
  else if (/камер|регистратор|nvr|dvr|видеонаблюд/.test(n)) key = "cctv";
  else if (/домофон|вызывн|внутренн.*монитор/.test(n)) key = "intercom";
  else if (/скуд|турникет|считыват|замок|терминал.*доступ|контрол.*доступ/.test(n)) key = "access";
  else if (/пожар|извещател/.test(n)) key = "fire";
  else if (/оповещ/.test(n)) key = "pa";
  else if (/сигнализац/.test(n)) key = "alarm";
  else if (/видеостен|диспле|монитор/.test(n)) key = "videowall";
  else if (/сервер|ибп|жёстк.*диск|жестк.*диск|хранилищ/.test(n)) key = "server";
  else if (/коммутатор|маршрутизатор|витая пара|скс|sfp|оптик|шкаф|кабель|точк.*доступ|wi-fi|wifi|радиомост|pon|телефон/.test(n)) key = "network";
  return key ? serviceByKey[key] ?? null : null;
}
