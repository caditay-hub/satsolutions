async function main() {
  initModels();
  await connectDb();

  const cat = await PortfolioCategory.findOne({ where: { slug: "videonablyudenie" } });
  const fields = {
    title: "ЖК TowerUp — оптическая линия связи между 8 домами и узел видеонаблюдения",
    excerpt:
      "Вторая очередь ЖК TowerUp в Ташкенте: SAT Solutions проложила 849 м подвесной оптики между восемью жилыми домами и собрала центральный узел видеонаблюдения — 24 сварки с проверкой рефлектометром, 8 оптических кроссов, архив 28 ТБ.",
    content: CONTENT,
    clientName: "ЖК TowerUp",
    clientTasks:
      "Связать видеонаблюдение восьми новых домов второй очереди (блок-секции 2/9–2/16) в одну систему: довести сигнал от каждого дома до центрального узла без потерь и наводок, с общим архивом и защитой от перебоев питания.",
    equipmentSupply: EQUIPMENT,
    location: "Ташкент, Сергелийский район",
    completedAt: new Date("2026-07-31T00:00:00Z"),
    portfolioCategoryId: cat ? cat.id : null,
    coverImageUrl: `${API}/uploads/portfolio/${SLUG}-cover.jpg?v=1`,
    galleryImageUrls: [1, 2, 3, 4, 5, 6].map((n) => `${API}/uploads/images/towerup-vols-${n}.webp`),
    seoTitle: "Прокладка ВОЛС между домами ЖК в Ташкенте — кейс TowerUp",
    seoDescription:
      "Кейс SAT Solutions: 849 м подвесной оптики между 8 домами ЖК TowerUp, 24 сварки с проверкой рефлектометром, узел видеонаблюдения с архивом 28 ТБ.",
    published: true,
  };

  const existing = await PortfolioProject.findOne({ where: { slug: SLUG } });
  if (existing) {
    await existing.update(fields);
    console.log("updated", existing.id);
  } else {
    // sortOrder 4: сразу после первого кейса TowerUp (3) — реальные фото остаются первыми
    const created = await PortfolioProject.create({ slug: SLUG, ...fields, publishedAt: new Date(), sortOrder: 4 } as any);
    console.log("created", created.id);
  }
  process.exit(0);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
